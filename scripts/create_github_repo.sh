#!/bin/sh
# Creates the GitHub repository for this project and publishes the first version.
# Run it once, from the project folder, with the GitHub CLI logged in (gh auth login):
#
#   sh scripts/create_github_repo.sh             # public repository
#   sh scripts/create_github_repo.sh --private   # private repository
#
set -e
cd "$(dirname "$0")/.."

REPO="ESP32-with-SX1302-Gateway"
DESC="Low-cost 8-channel LoRaWAN gateway running the Semtech SX1302_HAL (v2.1.0) natively on the ESP32, with no Raspberry Pi required."
TOPICS="lorawan,lora,lora-gateway,esp32,esp32-s3,sx1302,semtech,chirpstack,esp-idf,mqtt,iot,au915"
VISIBILITY="${1:---public}"

command -v gh >/dev/null || { echo "GitHub CLI (gh) not found"; exit 1; }
gh auth status >/dev/null 2>&1 || { echo "run 'gh auth login' first"; exit 1; }
[ -d .git ] && { echo "this folder is already a git repository (.git exists)"; exit 1; }

GH_USER=$(gh api user -q .login)
VER=$(sed -n 's/.*ESP32_SX1302_VERSION "\(.*\)".*/\1/p' main/packet_forwarder/loragw_version.h)
echo "user: $GH_USER  repo: $REPO  version: v$VER"

# README: placeholder -> your GitHub user
sed -i.bak "s/SEU_USUARIO/$GH_USER/g" README.md && rm -f README.md.bak

# Local repository
git init -q -b main
git add -A

# Safety check: nothing generated by the build may go into the commit
bad=$(git diff --cached --name-only | grep -E '^(build[^/]*|managed_components|logs|\.pio)/|^sdkconfig(\.esp32|\.esp32s3|\.old)?$|^dependencies\.lock$|^main/packet_forwarder/(webpage|global_json)\.h$' || true)
if [ -n "$bad" ]; then
	echo "ERROR: generated files in the commit (check .gitignore):"
	echo "$bad" | head -20
	rm -rf .git
	exit 1
fi
for f in sdkconfig.defaults sdkconfig.defaults.esp32s3 scripts/build.sh .github/workflows/build.yml; do
	git diff --cached --name-only | grep -qx "$f" || { echo "ERROR: $f is missing from the commit"; rm -rf .git; exit 1; }
done
echo "$(git diff --cached --name-only | wc -l) files in the first commit"

git commit -q -m "ESP32 with SX1302 Gateway v$VER: ESP32-WROOM-32U and ESP32-S3-WROOM-2 (N32R16V) targets"

# GitHub: create, add the remote "origin" and push
gh repo create "$REPO" "$VISIBILITY" --description "$DESC" --source=. --remote=origin --push
gh repo edit "$GH_USER/$REPO" --add-topic "$TOPICS"

# First tag: GitHub Actions builds both boards and publishes the Release with the .bin files
git tag -a "v$VER" -m "v$VER"
git push -q origin "v$VER"

echo
echo "https://github.com/$GH_USER/$REPO"
echo "build/release: https://github.com/$GH_USER/$REPO/actions"
